#!/bin/sh
# Host firewall for agent networks (DR-0005 amendment, open question 12). Agent networks live in
# 192.168.240.0/20, one /24 per agent with its gateway at .1 (AGENT_NET_POOL in packages/launcher/src/runtime.ts).
# These pf rules let each agent reach only its own egress proxy (gateway port 3128) and nothing else on this Mac:
# AirPlay, dev servers, anything listening on all interfaces. They load into Apple's existing `com.apple/*` anchor
# slot (no edit to /etc/pf.conf); a LaunchDaemon reloads them at boot.
#   sudo sh scripts/pf-agents.sh install     # write the rules + LaunchDaemon, load now
#   sudo sh scripts/pf-agents.sh status      # pf state and the loaded rules
#   sudo sh scripts/pf-agents.sh uninstall   # remove both, flush the rules (pf itself stays as it was)
#   sh scripts/pf-agents.sh rules            # print the rules (no sudo)
set -eu
ANCHOR="com.apple/cairn-agents"
RULES="/etc/pf.anchors/cairn-agents"
LABEL="com.cairn.pf-agents"
PLIST="/Library/LaunchDaemons/$LABEL.plist"
POOL="192.168.240.0/20"
FIRST=240
LAST=255
PROXY_PORT=3128

rules() {
  echo "# Cairn agent networks ($POOL): each agent reaches only its own egress proxy. Generated by scripts/pf-agents.sh."
  i=$FIRST
  while [ "$i" -le "$LAST" ]; do
    echo "pass in quick inet proto tcp from 192.168.$i.0/24 to 192.168.$i.1 port $PROXY_PORT flags S/SA keep state"
    i=$((i + 1))
  done
  echo "block return in quick inet from $POOL to any"
}

if [ "${1:-}" = rules ]; then rules; exit 0; fi
[ "$(id -u)" = 0 ] || { echo "run with sudo: sudo sh $0 ${1:-install}" >&2; exit 1; }

status() {
  pfctl -s info 2>/dev/null | head -n 1
  echo "rules in $ANCHOR:"
  pfctl -a "$ANCHOR" -s rules 2>/dev/null | sed 's/^/  /'
}

case "${1:-}" in
  install)
    rules > "$RULES.tmp"
    chown root:wheel "$RULES.tmp" && chmod 644 "$RULES.tmp" && mv "$RULES.tmp" "$RULES"
    pfctl -n -a "$ANCHOR" -f "$RULES"   # syntax check before anything is loaded
    cat > "$PLIST.tmp" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array><string>/sbin/pfctl</string><string>-E</string><string>-a</string><string>$ANCHOR</string><string>-f</string><string>$RULES</string></array>
  <key>RunAtLoad</key><true/>
</dict>
</plist>
EOF
    chown root:wheel "$PLIST.tmp" && chmod 644 "$PLIST.tmp" && mv "$PLIST.tmp" "$PLIST"
    launchctl bootout "system/$LABEL" 2>/dev/null || true
    launchctl bootstrap system "$PLIST"
    sleep 1
    status
    echo "installed. Verify from an agent: CAIRN_ESCAPE=1 corepack pnpm test:escape (test 4b)"
    ;;
  status) status ;;
  uninstall)
    launchctl bootout "system/$LABEL" 2>/dev/null || true
    pfctl -a "$ANCHOR" -F rules 2>/dev/null || true
    rm -f "$PLIST" "$RULES"
    echo "removed $LABEL and the $ANCHOR rules"
    ;;
  *) echo "usage: sudo sh $0 install|status|uninstall" >&2; exit 2 ;;
esac
